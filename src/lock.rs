//! The `sk.lock` record of resolved skills.

use serde::{Deserialize, Serialize};

use crate::ensure;
use crate::error::{Error, Result};
use crate::paths::Layout;

/// Lock format version written by this build of `sk`.
pub const LOCK_VERSION: u32 = 1;

/// Contents of `sk.lock`.
#[derive(Debug, Default, PartialEq, Eq, Deserialize, Serialize)]
#[serde(deny_unknown_fields)]
pub struct Lock {
    /// Lock format version.
    #[serde(default)]
    pub version: u32,
    /// One entry per installed skill.
    #[serde(default, rename = "skill")]
    pub skills: Vec<Entry>,
}

/// One resolved skill.
#[derive(Debug, Clone, PartialEq, Eq, Deserialize, Serialize)]
#[serde(deny_unknown_fields)]
pub struct Entry {
    /// Directory name under `.agents/skills`.
    pub name: String,
    /// Link as written in `sk.toml`.
    pub source: String,
    /// Commit the skill was downloaded from, so later runs are reproducible.
    pub commit: String,
}

impl Lock {
    /// Reads `sk.lock`, treating a missing file as an empty lock.
    pub fn load(layout: &Layout) -> Result<Self> {
        let path = layout.lock();
        let text = match std::fs::read_to_string(&path) {
            Ok(text) => text,
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => {
                return Ok(Self {
                    version: LOCK_VERSION,
                    skills: Vec::new(),
                });
            }
            Err(source) => {
                return Err(Error::with_source(
                    format!("could not read {}", path.display()),
                    source,
                ));
            }
        };

        let lock: Self = toml::from_str(&text).map_err(|source| {
            Error::with_source(format!("{} is invalid", path.display()), source)
        })?;

        ensure!(
            lock.version == LOCK_VERSION,
            "{} was written by another version of sk (lock version {}, expected {LOCK_VERSION}); delete it to re-resolve",
            path.display(),
            lock.version
        );
        Ok(lock)
    }

    /// Writes `sk.lock`, creating parent directories as needed.
    pub fn save(&self, layout: &Layout) -> Result<()> {
        let path = layout.lock();
        let body = toml::to_string_pretty(self)?;
        let contents = format!(
            "# Generated by sk {}. Do not edit by hand; edit sk.toml and run `sk sync`.\n{body}",
            env!("CARGO_PKG_VERSION")
        );
        crate::util::write_atomic(&path, contents.as_bytes())
    }

    /// Looks up a previously resolved commit for a link.
    pub fn commit_for(&self, source: &str) -> Option<&str> {
        self.skills
            .iter()
            .find(|entry| entry.source == source)
            .map(|entry| entry.commit.as_str())
    }

    /// Names of every skill `sk` has installed, used to prune removed ones.
    pub fn managed_names(&self) -> impl Iterator<Item = &str> {
        self.skills.iter().map(|entry| entry.name.as_str())
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::paths::Layout;

    fn temp_layout(name: &str) -> Layout {
        let dir = std::env::temp_dir().join(format!("sk-test-{name}-{}", std::process::id()));
        std::fs::remove_dir_all(&dir).ok();
        std::fs::create_dir_all(&dir).unwrap();
        Layout::new(dir)
    }

    #[test]
    fn missing_file_loads_as_empty() {
        let layout = temp_layout("missing");
        let lock = Lock::load(&layout).unwrap();
        assert_eq!(lock.version, LOCK_VERSION);
        assert!(lock.skills.is_empty());
        std::fs::remove_dir_all(layout.root).ok();
    }

    #[test]
    fn round_trips_and_finds_commits() {
        let layout = temp_layout("roundtrip");
        let lock = Lock {
            version: LOCK_VERSION,
            skills: vec![Entry {
                name: "demo".into(),
                source: "https://github.com/o/r/tree/main/demo".into(),
                commit: "abc123".into(),
            }],
        };
        lock.save(&layout).unwrap();

        let reloaded = Lock::load(&layout).unwrap();
        assert_eq!(reloaded, lock);
        assert_eq!(
            reloaded.commit_for("https://github.com/o/r/tree/main/demo"),
            Some("abc123")
        );
        assert_eq!(
            reloaded.commit_for("https://github.com/o/r/tree/main/other"),
            None
        );
        assert_eq!(reloaded.managed_names().collect::<Vec<_>>(), vec!["demo"]);
        std::fs::remove_dir_all(layout.root).ok();
    }

    #[test]
    fn rejects_a_foreign_lock_version() {
        let layout = temp_layout("version");
        std::fs::write(layout.lock(), "version = 99\n").unwrap();
        assert!(Lock::load(&layout).is_err());
        std::fs::remove_dir_all(layout.root).ok();
    }
}
